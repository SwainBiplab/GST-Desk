/**
 * Building a version of the HSN/SAC master: parse the curated CSV, write the data file, sign a
 * manifest over its hash, and point the app's bundled-version loader at it.
 */
import { createPrivateKey, createPublicKey, generateKeyPairSync, sign } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  manifestMessage,
  parseHsnCsv,
  sha256Hex,
  verifyHsnManifest,
  type HsnDataFile,
  type HsnManifest,
  type HsnParseError,
} from '@gst/domain';

export interface PublicKeyFile {
  keyId: string;
  algorithm: 'ed25519';
  /** Raw 32-byte public key, base64. */
  publicKeyBase64: string;
}

export class SourceError extends Error {
  override name = 'SourceError';
  constructor(readonly errors: HsnParseError[]) {
    super(
      `${errors.length} problem(s) in the source file:\n${errors.map((e) => `  line ${e.line}: ${e.message}`).join('\n')}`,
    );
  }
}

export interface BuildOptions {
  csvText: string;
  outDir: string;
  version: string;
  asOf: string;
  source: string;
  privateKeyPem: string;
  keyId: string;
  /** Rewrite `bundled.ts` so the app ships this version. */
  bundle?: boolean;
}

/** One row per line keeps diffs readable; the result is still plain JSON. */
export function serialiseData(data: HsnDataFile): string {
  const head = JSON.stringify({
    version: data.version,
    as_of: data.as_of,
    source: data.source,
  }).slice(0, -1);
  const rows = data.rows.map((r) => JSON.stringify(r)).join(',\n');
  return `${head},"rows":[\n${rows}\n]}\n`;
}

export async function buildHsnVersion(
  o: BuildOptions,
): Promise<{ data: HsnDataFile; manifest: HsnManifest }> {
  const parsed = parseHsnCsv(o.csvText);
  if (parsed.errors.length > 0) throw new SourceError(parsed.errors);
  if (!/^\d+(\.\d+)*$/.test(o.version))
    throw new Error(`version "${o.version}" must look like 2025.9.1`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(o.asOf)) throw new Error(`as-of "${o.asOf}" must be YYYY-MM-DD`);

  const rows = [...parsed.rows].sort(
    (a, b) => a.code.localeCompare(b.code) || a.effective_from.localeCompare(b.effective_from),
  );
  const data: HsnDataFile = { version: o.version, as_of: o.asOf, source: o.source, rows };
  const dataText = serialiseData(data);

  const base = {
    version: o.version,
    as_of: o.asOf,
    count: rows.length,
    sha256: await sha256Hex(dataText),
  };
  const signature = sign(
    null,
    Buffer.from(manifestMessage(base)),
    createPrivateKey(o.privateKeyPem),
  );
  const manifest: HsnManifest = {
    ...base,
    file: `hsn-v${o.version}.json`,
    keyId: o.keyId,
    signature: signature.toString('base64'),
  };

  await mkdir(o.outDir, { recursive: true });
  await writeFile(join(o.outDir, manifest.file), dataText);
  await writeFile(
    join(o.outDir, `hsn-v${o.version}.manifest.json`),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  if (o.bundle !== false) await writeFile(join(o.outDir, 'bundled.ts'), bundledModule(o.version));
  return { data, manifest };
}

/** The module the app imports to get the version that ships inside the installer. */
export function bundledModule(version: string): string {
  return `// Generated by tools/hsn (pnpm hsn:build). Do not edit.
import type { HsnDataFile, HsnManifest } from '../src/hsn';

export const BUNDLED_HSN_VERSION = '${version}';

/**
 * Loaded on demand so the master stays out of the first-load bundle. \`dataText\` is the file exactly
 * as signed: the signature covers its bytes, so it must be verified before it is parsed.
 */
export async function loadBundledHsn(): Promise<{
  dataText: string;
  data: HsnDataFile;
  manifest: HsnManifest;
}> {
  const [text, manifest] = await Promise.all([
    import('./hsn-v${version}.json?raw'),
    import('./hsn-v${version}.manifest.json'),
  ]);
  return {
    dataText: text.default,
    data: JSON.parse(text.default) as HsnDataFile,
    manifest: manifest.default as HsnManifest,
  };
}
`;
}

/** Create a signing key pair. The private key is returned as PEM; only the public half belongs in git. */
export function generateKeys(keyId: string): { privateKeyPem: string; publicKey: PublicKeyFile } {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const raw = publicKey.export({ format: 'der', type: 'spki' }).subarray(-32);
  return {
    privateKeyPem: privateKey.export({ format: 'pem', type: 'pkcs8' }).toString(),
    publicKey: { keyId, algorithm: 'ed25519', publicKeyBase64: raw.toString('base64') },
  };
}

/** The public key that matches a private key, for checking a key file before using it. */
export function publicKeyOf(privateKeyPem: string): string {
  const pub = createPublicKey(createPrivateKey(privateKeyPem));
  return pub.export({ format: 'der', type: 'spki' }).subarray(-32).toString('base64');
}

export interface VerifyReport {
  file: string;
  version: string;
  ok: boolean;
  reason?: string;
}

/** Verify every manifest in `dir` against `publicKey`. */
export async function verifyDirectory(
  dir: string,
  publicKey: PublicKeyFile,
): Promise<VerifyReport[]> {
  const names = (await readdir(dir)).filter((n) => /^hsn-v.+\.manifest\.json$/.test(n)).sort();
  const out: VerifyReport[] = [];
  for (const name of names) {
    const manifest = JSON.parse(await readFile(join(dir, name), 'utf8')) as HsnManifest;
    const dataText = await readFile(join(dir, manifest.file), 'utf8');
    const r = await verifyHsnManifest({ manifest, dataText, publicKey });
    out.push({
      file: name,
      version: manifest.version,
      ok: r.ok,
      ...(r.ok ? {} : { reason: r.reason }),
    });
  }
  return out;
}
