/**
 * What a GSP or portal error means, in plain words, and what to do. Vendor codes vary; these are the
 * portal's own codes as documented publicly, plus the codes our adapters raise themselves (prefixed
 * `GD-`). STATUS: the portal codes are NOT verified against a sandbox (B-111); an unknown code shows the
 * portal's own message.
 */
export interface GspErrorInfo {
  /** What happened, for the person. */
  plain: string;
  /** What to do next. */
  next: string;
  /** Trying again later may work (a network or token problem), so the queue retries it. */
  retry: boolean;
}

