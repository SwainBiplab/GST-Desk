/** Plain words for a code; an unknown code keeps the portal's own message. */
export function explainGspError(code: string, portalMessage = ''): GspErrorInfo {
  return (
    GSP_ERRORS[code] ?? {
      plain: portalMessage || `The portal returned error ${code}.`,
      next: 'Check the document, or ask your GSP or the GST helpdesk with this code.',
      retry: false,
    }
  );
}
