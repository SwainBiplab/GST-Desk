/** Collects Drizzle Kit SQL + generated extras into src/migrations.generated.ts (embedded for Tauri/PWA). */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { extrasSql, gstExtrasSql, purgeSql, searchLatinSql } from '../src/schema/extras';

const root = join(import.meta.dirname, '..');
const out: Record<string, { name: string; sql: string }[]> = {};

for (const dialect of ['sqlite', 'pg'] as const) {
  const dir = join(root, 'migrations', dialect);
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort();
  out[dialect] = files.map((f) => ({
    name: f.replace(/\.sql$/, ''),
    sql: readFileSync(join(dir, f), 'utf8'),
  }));
  out[dialect]!.push({ name: '9000_extras_v1', sql: extrasSql(dialect) });
  out[dialect]!.push({ name: '9001_trash_purge', sql: purgeSql(dialect) });
  out[dialect]!.push({ name: '9002_search_latin', sql: searchLatinSql(dialect) });
  out[dialect]!.push({ name: '9003_extras_gst', sql: gstExtrasSql(dialect) });
}

const body = `// GENERATED by scripts/build-migrations.ts. Do not edit.
export interface Migration {
  name: string;
  sql: string;
}

export const MIGRATIONS: Record<'sqlite' | 'pg', Migration[]> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'src', 'migrations.generated.ts'), body);
console.log(
  'wrote migrations.generated.ts',
  Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])),
);
